"""Markdown for the generated reports and the command line."""

from __future__ import annotations

from datetime import datetime

from playbooks import rules
from playbooks.engine import Plan, plan
from playbooks.model import Library, Policy

NOT_LEGAL_ADVICE = (
    "This is a planning aid for organising an incident response. It is not legal advice and does not say "
    "what any law requires. Notification deadlines in the example are placeholders to be set and reviewed "
    "with your own legal team."
)


def table(headers: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(c.replace("|", "\\|") for c in row) + " |" for row in rows]
    return "\n".join(out) + "\n"


def _when(when: dict[str, object]) -> str:
    parts = []
    for k, v in when.items():
        if isinstance(v, tuple):
            parts.append(f"{k.removesuffix('_in').replace('_', ' ')} in {', '.join(v)}")
        elif k.endswith("_min"):
            parts.append(f"{k.removesuffix('_min').replace('_', ' ')} at least {v}")
        else:
            parts.append(f"{k.replace('_', ' ')} = {str(v).lower()}")
    return "; ".join(parts) or "always"


def policy_markdown(p: Policy) -> str:
    out = [
        "# Policy\n",
        "Generated by `aip report`. Edit `policy/policy.toml`, not this file.\n",
        NOT_LEGAL_ADVICE + "\n",
    ]
    out.append("## Severity levels\n")
    out.append(
        table(
            ["Level", "Acknowledge within", "Update at least every", "Contain within"],
            [
                [
                    f"`{lv.name}`",
                    f"{lv.ack_minutes} min",
                    f"{lv.update_minutes} min",
                    f"{p.contain_within[lv.name]} min" if lv.name in p.contain_within else "-",
                ]
                for lv in p.levels
            ],
        )
    )
    out.append(
        "\nAn incident is run at the most severe level of what was declared and what any rule below gives.\n"
    )
    out.append("## Severity rules\n")
    out.append(
        table(
            ["Level", "When", "Because"],
            [[f"`{r.level}`", _when(r.when), r.because] for r in p.rules],
        )
    )
    out.append("\n## Roles\n")
    out.append(
        table(
            ["Role", "Backup", "People"],
            [
                [
                    f"`{n}`",
                    f"`{r.backup}`" if r.backup else ("final" if r.final else "-"),
                    ", ".join(f"`{x}`" for x, roles in sorted(p.people.items()) if n in roles)
                    or "-",
                ]
                for n, r in sorted(p.roles.items())
            ],
        )
    )
    out.append("\n## Notification obligations\n")
    out.append(
        table(
            ["Id", "Kind", "Audience", "When", "Clock", "Hours", "Status"],
            [
                [
                    f"`{o.id}`",
                    o.kind,
                    o.audience,
                    _when(o.when),
                    f"from {o.clock_from}",
                    str(o.deadline_hours),
                    "PLACEHOLDER"
                    if o.example
                    else ("reviewed " + o.reviewed_on if o.reviewed_on else "-"),
                ]
                for o in p.obligations
            ],
        )
    )
    return "\n".join(out) + "\n"


def playbooks_markdown(lib: Library) -> str:
    p = lib.policy
    out = [
        "# Playbooks\n",
        "Generated by `aip report`. Edit the files in `playbooks/`, not this file.\n",
    ]
    for k in sorted(lib.playbooks):
        pb = lib.playbooks[k]
        out.append(f"## {pb.title} (`{pb.id}`)\n")
        out.append(f"Applies to: {', '.join(f'`{x}`' for x in pb.applies_to)}\n")
        order = {ph: i for i, ph in enumerate(p.phases)}
        rows = []
        for s in sorted(
            pb.steps, key=lambda s: (order.get(s.phase, 99), min(s.due.values(), default=0))
        ):
            due = ", ".join(f"{lv} {s.due[lv]}m" for lv in p.level_names() if lv in s.due)
            rows.append(
                [
                    f"`{s.id}`",
                    s.phase,
                    f"`{s.role}`",
                    s.action,
                    due,
                    ", ".join(f"`{r}`" for r in s.requires) or "-",
                    (s.notifies and f"`{s.notifies}`") or "-",
                ]
            )
        out.append(
            table(
                ["Step", "Phase", "Role", "Action", "Due after declaration", "Needs", "Notifies"],
                rows,
            )
        )
    return "\n".join(out) + "\n"


def coverage_markdown(lib: Library) -> str:
    p = lib.policy
    out = ["# Coverage\n", "Generated by `aip report`.\n", "## Incident kinds\n"]
    out.append(
        table(
            ["Kind", "Playbooks"],
            [
                [
                    f"`{k}`",
                    ", ".join(f"`{pb.id}`" for pb in lib.playbooks.values() if k in pb.applies_to)
                    or "NONE",
                ]
                for k in p.kinds
            ],
        )
    )
    out.append("\n## Notification obligations\n")
    rows = []
    for o in p.obligations:
        pbs = sorted(
            pb.id for pb in lib.playbooks.values() if any(s.notifies == o.id for s in pb.steps)
        )
        rows.append([f"`{o.id}`", ", ".join(f"`{x}`" for x in pbs) or "NONE"])
    out.append(table(["Obligation", "Satisfied by a step in"], rows))
    return "\n".join(out) + "\n"


def _state(s: str, late: bool) -> str:
    return "done late" if s == "done" and late else s


def plan_text(pl: Plan) -> str:
    out = [f"{pl.incident}: run at {pl.level} (declared {pl.declared}, facts give {pl.computed})"]
    out += [f"  because: {r}" for r in pl.reasons]
    out.append(
        f"  acknowledge by {pl.ack_due.isoformat()}: "
        + ("DONE" if pl.ack_done_at else ("OVERDUE" if pl.ack_overdue else "open"))
    )
    out.append(
        f"  next update by {pl.update_due.isoformat()}"
        + (" (OVERDUE)" if pl.update_overdue else "")
    )
    out.append("  steps:")
    for s in pl.steps:
        out.append(
            f"    {_state(s.status, s.late):10} {s.step.id}  [{s.step.phase}, {s.step.role}] due {s.due.isoformat()}"
        )
    out.append("  notifications:")
    if not pl.obligations:
        out.append("    none apply")
    for o in pl.obligations:
        out.append(
            f"    {_state(o.status, o.late):10} {o.obligation.id} ({o.obligation.audience}) due {o.due.isoformat()}"
        )
    return "\n".join(out)


def incidents_markdown(lib: Library, now: datetime) -> str:
    out = ["# Incidents\n", f"Generated by `aip report --now {now.isoformat()}`.\n"]
    rows = []
    for k in sorted(lib.incidents):
        inc = lib.incidents[k]
        pl = plan(lib, inc, now)
        if pl is None:
            rows.append([f"`{inc.id}`", inc.title, inc.status, "-", "-", "-", "-"])
            continue
        done = sum(1 for s in pl.steps if s.status == "done")
        rows.append(
            [
                f"`{inc.id}`",
                inc.title,
                inc.status,
                pl.level,
                f"{done} of {len(pl.steps)}",
                ", ".join(pl.overdue_steps()) or "-",
                ", ".join(pl.overdue_obligations()) or "-",
            ]
        )
    out.append(
        table(
            [
                "Incident",
                "Title",
                "Status",
                "Level",
                "Steps done",
                "Overdue steps",
                "Overdue notifications",
            ],
            rows,
        )
    )
    return "\n".join(out) + "\n"


def drills_markdown(results: list[tuple[str, str, list[str]]]) -> str:
    out = [
        "# Drills\n",
        "Generated by `aip report`. A drill replays a scripted incident and checks the playbook gives the expected state at a stated time.\n",
    ]
    out.append(
        table(
            ["Drill", "Result", "Differences"],
            [[f"`{n}`", r, "; ".join(d) or "-"] for n, r, d in results],
        )
    )
    return "\n".join(out) + "\n"


def findings_markdown(findings: list[rules.Finding]) -> str:
    out = ["# Lint\n", "Generated by `aip report`.\n"]
    if not findings:
        return "\n".join(out) + "\nNo findings.\n"
    out.append(
        table(
            ["Severity", "Rule", "Subject", "Message"],
            [[f.severity, f.rule, f"`{f.subject}`", f.message] for f in findings],
        )
    )
    return "\n".join(out) + "\n"


def rules_markdown() -> str:
    out = ["# Lint rules\n", "Generated by `aip report`.\n"]
    out.append(
        table(
            ["Rule", "Severity", "What it checks", "Why it matters"],
            [[f"`{r.id}`", r.severity, r.title, r.why] for r in rules.REGISTRY],
        )
    )
    return "\n".join(out) + "\n"
